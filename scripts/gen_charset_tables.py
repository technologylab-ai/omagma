import codecs
single = [
 ("windows-1250","cp1250"),("windows-1251","cp1251"),("windows-1252","cp1252"),("windows-1253","cp1253"),("windows-1254","cp1254"),
 ("windows-1255","cp1255"),("windows-1256","cp1256"),("windows-1257","cp1257"),("windows-1258","cp1258"),
 ("iso-8859-1","latin_1"),("iso-8859-2","iso8859_2"),("iso-8859-3","iso8859_3"),("iso-8859-4","iso8859_4"),("iso-8859-5","iso8859_5"),
 ("iso-8859-6","iso8859_6"),("iso-8859-7","iso8859_7"),("iso-8859-8","iso8859_8"),("iso-8859-9","iso8859_9"),("iso-8859-10","iso8859_10"),
 ("iso-8859-11","iso8859_11"),("iso-8859-13","iso8859_13"),("iso-8859-14","iso8859_14"),("iso-8859-15","iso8859_15"),("iso-8859-16","iso8859_16"),
 ("koi8-r","koi8_r"),("koi8-u","koi8_u"),("ibm850","cp850"),("ibm437","cp437"),("ibm852","cp852"),("ibm866","cp866"),
 ("macintosh","mac_roman"),("windows-874","cp874"),
]
out = ["//! Generated by a maintainer script from the Python standard-library codecs.",
       "//! Each table maps bytes 0x80-0xFF to a BMP code point; 0xFFFD marks an",
       "//! undefined byte. Do not edit by hand.",
       "pub const Table = struct { name: []const u8, map: [128]u16 };",
       "pub const tables = [_]Table{"]
for name, codec in single:
    vals=[]
    for b in range(128,256):
        try:
            ch = bytes([b]).decode(codec)
            cp = ord(ch)
            # C1 controls carry no display meaning; windows-1252 leaves five undefined.
            vals.append(cp if cp <= 0xFFFF else 0xFFFD)
        except UnicodeDecodeError:
            vals.append(0xFFFD)
    rows = ["        " + " ".join("0x%04x," % v for v in vals[i:i+8]) for i in range(0,128,8)]
    out.append('    .{ .name = "%s", .map = .{\n%s\n    } },' % (name, "\n".join(rows)))
out.append("};")
open("src/terminal/charset_tables.zig","w").write("\n".join(out)+"\n")
