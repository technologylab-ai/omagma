const Completed = struct {
    pub fn await(_: *@This(), _: std.Io) void {}
    pub fn cancel(_: *@This(), _: std.Io) void {}
};
pub const Job = if (browser) Completed else std.Io.Future(void);

/// Callers finish an inline browser job only after assigning the returned
/// marker, so the worker cannot observe a half-installed future. Native callers
/// continue receiving the same concurrent future and completion event.
pub fn launch(io: std.Io, comptime function: anytype, arguments: anytype) !Job {
    if (browser) {
        @call(.auto, function, arguments);
        return .{};
    }
    return io.concurrent(function, arguments);
}
pub fn postEvent(loop: anytype, event: anytype) !bool {
    if (browser) return false;
    return loop.tryPostEvent(event);
}
pub fn postEventBlocking(loop: anytype, event: anytype) !void {
    if (browser) return;
    return loop.postEvent(event);
}

/// A browser session's nonce is generated by the host before connecting and
/// contains no account data or credentials. Never wrap its operation counter.
pub fn sessionOperationId(a: std.mem.Allocator, nonce: []const u8, sequence: *u64) ![]const u8 {
    if (nonce.len != 36) return error.InvalidSessionNonce;
    for (nonce, 0..) |byte, index| {
        if (index == 8 or index == 13 or index == 18 or index == 23) {
            if (byte != '-') return error.InvalidSessionNonce;
        } else if (!std.ascii.isHex(byte)) return error.InvalidSessionNonce;
    }
    if (sequence.* == std.math.maxInt(u64)) return error.OperationCounterExhausted;
    sequence.* += 1;
    return std.fmt.allocPrint(a, "browser-{s}-{d}", .{ nonce, sequence.* });
}
pub fn operationId(io: std.Io, a: std.mem.Allocator, nonce: ?[]const u8, sequence: *u64) ![]const u8 {
    if (browser) return sessionOperationId(a, nonce orelse return error.InvalidSessionNonce, sequence);
    var random: [16]u8 = undefined;
    try io.randomSecure(&random);
    const hex = std.fmt.bytesToHex(random, .lower);
    return std.fmt.allocPrint(a, "tui-{s}", .{hex});
}

test "platform: session entropy increments without account information and refuses reuse on exhaustion" {
    const a = std.testing.allocator;
    var sequence: u64 = 0;
    const first = try sessionOperationId(a, "12345678-1234-5678-90ab-123456789abc", &sequence);
    defer a.free(first);
    const next = try sessionOperationId(a, "12345678-1234-5678-90ab-123456789abc", &sequence);
    defer a.free(next);
    try std.testing.expectEqualStrings("browser-12345678-1234-5678-90ab-123456789abc-1", first);
    try std.testing.expectEqualStrings("browser-12345678-1234-5678-90ab-123456789abc-2", next);
    try std.testing.expectError(error.InvalidSessionNonce, sessionOperationId(a, "not-a-session", &sequence));
    sequence = std.math.maxInt(u64);
    try std.testing.expectError(error.OperationCounterExhausted, sessionOperationId(a, "12345678-1234-5678-90ab-123456789abc", &sequence));
}

test "platform: native launch remains a future and completion events retain their result" {
    var complete: std.atomic.Value(bool) = .init(false);
    var job = try launch(std.testing.io, struct {
        fn work(done: *std.atomic.Value(bool)) void {
            done.store(true, .release);
        }
    }.work, .{&complete});
    job.await(std.testing.io);
    try std.testing.expect(complete.load(.acquire));
    const Loop = struct {
        events: usize = 0,
        pub fn tryPostEvent(self: *@This(), _: enum { done }) !bool {
            self.events += 1;
            return true;
        }
    };
    var loop: Loop = .{};
    const posted = try postEvent(&loop, .done);
    try std.testing.expectEqual(!browser, posted);
    try std.testing.expectEqual(@as(usize, if (browser) 0 else 1), loop.events);
}
