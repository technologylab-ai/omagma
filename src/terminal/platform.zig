//! Platform edges for the shared terminal application. The browser executes a
//! worker inline through JSPI; native terminals retain their existing future.
const std = @import("std");
const builtin = @import("builtin");
pub const browser = builtin.cpu.arch == .wasm32 and builtin.os.tag == .freestanding;

